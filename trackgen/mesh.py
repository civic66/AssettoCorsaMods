"""Mesh building and OBJ/MTL export.

All geometry is built in the local frame (x = east, y = north, z = up, metres),
which is also Blender's frame. OBJ output is written Y-up (x, z, -y), the
convention Blender's OBJ importer expects by default.

Assetto Corsa naming rules used here:
  <n>ROAD, <n>GRASS -> physical surfaces, <n>WALL -> collision walls (n = number)
  anything else                  -> visual only
  Meshes are split so no object exceeds 65k vertices (KN5 uses 16-bit indices).
"""
import numpy as np

MAX_VERTS = 60000


class Mesh:
    def __init__(self, name, material):
        self.name = name
        self.material = material
        self.v = []
        self.uv = []
        self.f = []

    def add_grid(self, verts, uvs, flip=False, mask=None):
        """verts, uvs: (rows, cols, 3) / (rows, cols, 2). Adds a quad grid.
        mask: optional (rows-1, cols-1) bool array of quads to keep."""
        rows, cols = verts.shape[:2]
        base = sum(len(a) for a in self.v)
        self.v.append(verts.reshape(-1, 3))
        self.uv.append(uvs.reshape(-1, 2))
        r, c = np.meshgrid(np.arange(rows - 1), np.arange(cols - 1), indexing="ij")
        i00 = base + r * cols + c
        i01 = i00 + 1
        i10 = i00 + cols
        i11 = i10 + 1
        if flip:
            tris = [np.stack([i00, i01, i10], -1), np.stack([i01, i11, i10], -1)]
        else:
            tris = [np.stack([i00, i10, i01], -1), np.stack([i01, i10, i11], -1)]
        if mask is not None:
            tris = [t[mask] for t in tris]
        self.f.append(np.concatenate([t.reshape(-1, 3) for t in tris]))

    def compact(self):
        """Drop vertices not referenced by any face."""
        v, uv, f = self.vertices, self.uvs, self.faces
        used = np.unique(f)
        remap = np.full(len(v), -1)
        remap[used] = np.arange(len(used))
        self.v, self.uv, self.f = [v[used]], [uv[used]], [remap[f]]

    @property
    def vertices(self):
        return np.concatenate(self.v) if self.v else np.zeros((0, 3))

    @property
    def uvs(self):
        return np.concatenate(self.uv) if self.uv else np.zeros((0, 2))

    @property
    def faces(self):
        return np.concatenate(self.f) if self.f else np.zeros((0, 3), dtype=int)

    def normals(self):
        v, f = self.vertices, self.faces
        n = np.zeros_like(v)
        fn = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
        for k in range(3):
            np.add.at(n, f[:, k], fn)
        ln = np.linalg.norm(n, axis=1, keepdims=True)
        ln[ln == 0] = 1
        return n / ln


def strip_chunks(n_rows, cols, max_verts=MAX_VERTS):
    """Yield (start, end) row ranges (inclusive end, overlapping by one row)."""
    per = max(2, max_verts // cols)
    start = 0
    while start < n_rows - 1:
        end = min(start + per - 1, n_rows - 1)
        yield start, end
        start = end


def write_obj(meshes, obj_path, mtl_name):
    lines = ["# generated by trackgen", f"mtllib {mtl_name}"]
    vo = 1
    for m in meshes:
        v, uv, f, n = m.vertices, m.uvs, m.faces, m.normals()
        if len(f) == 0:
            continue
        lines.append(f"o {m.name}")
        # local (east, north, up) -> OBJ Y-up (x, y, z) = (east, up, -north)
        lines.extend(f"v {a:.4f} {c:.4f} {-b:.4f}" for a, b, c in v)
        lines.extend(f"vt {a:.5f} {b:.5f}" for a, b in uv)
        lines.extend(f"vn {a:.4f} {c:.4f} {-b:.4f}" for a, b, c in n)
        lines.append(f"usemtl {m.material}")
        lines.append("s 1")
        ff = f + vo
        lines.extend(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}" for a, b, c in ff)
        vo += len(v)
    obj_path.write_text("\n".join(lines) + "\n")


def write_mtl(path, materials):
    out = []
    for name, tex in materials.items():
        out += [f"newmtl {name}", "Ka 1 1 1", "Kd 1 1 1", "Ks 0 0 0", "d 1", "illum 1"]
        if tex:
            out.append(f"map_Kd {tex}")
        out.append("")
    path.write_text("\n".join(out))
